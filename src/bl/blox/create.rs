use super::context;
use super::context::map_error;
use super::output::status_text;
use crate::bl::display::{print_json, terminal_safe_text};
use crate::bl::skills_api::{exit_codes, failure};
use crate::bl::skills_config::SkillsConfig;
use anyhow::{Context, Result};
use blox::proto::{ComputeSkuSelection, StartWorkstationRequest};
use clap::{Arg, ArgMatches, Command};
pub(super) fn command() -> Command {
    Command::new("create")
                .about("Create a new workstation with a SKU and multiple")
                .long_about("Create a new workstation without requesting project repositories. The deployment may still bootstrap its configured home repository. Returns the initial ID and status; creation continues on the server.")
                .arg(Arg::new("name").value_name("NAME").value_parser(clap::builder::NonEmptyStringValueParser::new()).help("Optional workstation name (otherwise generated by the server)"))
                .arg(Arg::new("sku").long("sku").value_name("CODE").default_value("DEFAULT_AMD64").value_parser(clap::builder::NonEmptyStringValueParser::new()).help("SKU code from `bl compute skus`"))
                .arg(Arg::new("multiple").long("multiple").value_name("COUNT").default_value("1").value_parser(clap::value_parser!(i32).range(1..)).help("SKU multiple"))
}

pub(super) fn run(config: &SkillsConfig, args: &ArgMatches) -> Result<()> {
    let client = context::client(config, args, "create")?;
    let request = StartWorkstationRequest {
        name: args.get_one::<String>("name").cloned(),
        compute_sku: Some(ComputeSkuSelection {
            code: args
                .get_one::<String>("sku")
                .context("expected SKU code")?
                .clone(),
            multiple: *args
                .get_one::<i32>("multiple")
                .context("expected SKU multiple")?,
        }),
        creation_client: "builderlab_cli".to_string(),
        ..Default::default()
    };
    let response = client
        .start_workstation(&request)
        .map_err(map_create_error)?;
    if response.workstation_id.is_empty() {
        return Err(create_unknown_outcome());
    }
    if config.json {
        print_json(&response)
    } else {
        println!("ID: {}", terminal_safe_text(&response.workstation_id));
        println!("Status: {}", status_text(response.status));
        if !response.message.is_empty() {
            println!("Message: {}", terminal_safe_text(&response.message));
        }
        println!(
            "Inspect with `bl compute get {}` (preserve any --base-url override).",
            terminal_safe_text(&response.workstation_id)
        );
        Ok(())
    }
}

fn create_unknown_outcome() -> anyhow::Error {
    failure(exit_codes::NETWORK, "create_outcome_unknown", "Blox creation result is unknown. Inspect `bl compute list` or `bl compute get <name>` before trying again; the workstation may already exist. Preserve any --base-url override when checking.")
}

fn map_create_error(error: anyhow::Error) -> anyhow::Error {
    if let Some(rpc) = error.downcast_ref::<blox::RpcError>() {
        if !matches!(
            rpc.code.as_str(),
            "unavailable" | "deadline_exceeded" | "unknown" | "internal" | "data_loss"
        ) {
            return map_error(error);
        }
    }
    create_unknown_outcome()
}

#[cfg(test)]
mod tests {
    use super::super::test_support::*;
    use serde_json::{json, Value};

    #[test]
    fn create_sends_only_the_selected_sku_multiple_and_optional_name() {
        let auth = auth_service();
        let service = MockService::start(
            200,
            json!({"workstationId":"1234567890123456789", "status":"WORKSTATION_STATUS_PENDING", "message":"awaiting approval"}),
        );
        let output = run_process(
            &auth,
            &service,
            &[
                "compute",
                "create",
                "test-name",
                "--sku",
                "CUSTOM_SKU",
                "--multiple",
                "3",
                "--base-url",
                "https://blox.test.blockstaging.build",
                "--json",
            ],
        );
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        assert_eq!(
            output_json(&output),
            json!({"workstationId":"1234567890123456789", "status":"WORKSTATION_STATUS_PENDING", "message":"awaiting approval"})
        );
        let (path, request) = assert_shared_auth(auth, service);
        assert!(path.ends_with(".OrchestratorService/StartWorkstation"));
        assert_eq!(
            request,
            json!({"name":"test-name", "computeSku":{"code":"CUSTOM_SKU", "multiple":3}, "creationClient":"builderlab_cli"})
        );
    }

    #[test]
    fn create_defaults_the_sku_and_multiple_and_leaves_name_to_the_server() {
        let auth = auth_service();
        let service = MockService::start(
            200,
            json!({"workstationId":"123", "status":"WORKSTATION_STATUS_QUEUED"}),
        );
        let output = run_process(
            &auth,
            &service,
            &[
                "compute",
                "create",
                "--base-url",
                "https://blox.test.blockstaging.build",
            ],
        );
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        let stdout = String::from_utf8_lossy(&output.stdout);
        assert!(stdout.contains("ID: 123"));
        assert!(stdout.contains("Status: queued"));
        assert!(!stdout.contains("ready"));
        let (_, request) = assert_shared_auth(auth, service);
        assert_eq!(
            request,
            json!({"computeSku":{"code":"DEFAULT_AMD64", "multiple":1}, "creationClient":"builderlab_cli"})
        );
    }

    #[test]
    fn create_rejected_session_stops_before_the_mutation() {
        let auth = MockService::start(401, json!({"error":"expired"}));
        let output = run_process(
            &auth,
            &auth,
            &[
                "compute",
                "create",
                "--base-url",
                "https://blox.test.blockstaging.build",
                "--json",
            ],
        );
        assert_eq!(output.status.code(), Some(3));
        let payload: Value = serde_json::from_slice(&output.stderr).unwrap();
        assert_eq!(payload["error"]["code"], "auth_required");
        let (path, _, _) = auth.finish();
        assert_eq!(path, "/api/goose/v1/auth/me");
    }

    #[test]
    fn create_preserves_definite_server_rejections() {
        let auth = auth_service();
        let service = MockService::start(
            400,
            json!({"code":"invalid_argument", "message":"SKU multiple exceeds your maximum"}),
        );
        let output = run_process(
            &auth,
            &service,
            &[
                "compute",
                "create",
                "--multiple",
                "9",
                "--base-url",
                "https://blox.test.blockstaging.build",
                "--json",
            ],
        );
        assert_eq!(output.status.code(), Some(1));
        let payload: Value = serde_json::from_slice(&output.stderr).unwrap();
        assert_eq!(payload["error"]["code"], "invalid_argument");
        assert!(payload["error"]["message"]
            .as_str()
            .unwrap()
            .contains("maximum"));
        assert_shared_auth(auth, service);
    }

    #[test]
    fn create_ambiguous_results_require_inspection_before_retrying() {
        for (status, response) in [
            (
                503,
                json!({"code":"unavailable", "message":"lost response"}),
            ),
            (200, json!("unexpected response")),
            (200, json!({"status":"WORKSTATION_STATUS_CREATING"})),
        ] {
            let auth = auth_service();
            let service = MockService::start(status, response);
            let output = run_process(
                &auth,
                &service,
                &[
                    "compute",
                    "create",
                    "--base-url",
                    "https://blox.test.blockstaging.build",
                    "--json",
                ],
            );
            assert_eq!(output.status.code(), Some(5));
            let payload: Value = serde_json::from_slice(&output.stderr).unwrap();
            assert_eq!(payload["error"]["code"], "create_outcome_unknown");
            let message = payload["error"]["message"].as_str().unwrap();
            assert!(message.contains("before trying again"));
            assert!(message.contains("--base-url"));
            assert_shared_auth(auth, service);
        }
    }
}
