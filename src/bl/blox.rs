pub fn command() -> Command {
    endpoint_arg(Command::new("blox")
        .about("Manage Blox workstations")
        .long_about("Manage your Blox workstations using your BuilderLab login. Names are resolved by the orchestrator; use the full ID to identify an archived workstation.")
        .subcommand_required(true)
        .arg_required_else_help(true)
        .disable_help_subcommand(true)
        .subcommand(
            Command::new("list")
                .about("List your workstations")
                .arg(Arg::new("include-deleted").long("include-deleted").action(ArgAction::SetTrue).help("Include archived workstations"))
                .arg(Arg::new("limit").long("limit").value_name("COUNT").value_parser(clap::value_parser!(i32).range(0..)).default_value("100").help("Maximum results (0 means all)"))
                .arg(Arg::new("offset").long("offset").value_name("COUNT").value_parser(clap::value_parser!(i32).range(0..)).default_value("0").help("Number of results to skip")),
        )
        .subcommand(Command::new("skus").about("List available workstation SKUs and maximum multiples"))
        .subcommand(
            Command::new("create")
                .about("Create a new workstation with a SKU and multiple")
                .long_about("Create a new workstation without requesting project repositories. The deployment may still bootstrap its configured home repository. Returns the initial ID and status; creation continues on the server.")
                .arg(Arg::new("name").value_name("NAME").value_parser(clap::builder::NonEmptyStringValueParser::new()).help("Optional workstation name (otherwise generated by the server)"))
                .arg(Arg::new("sku").long("sku").value_name("CODE").default_value("DEFAULT_AMD64").value_parser(clap::builder::NonEmptyStringValueParser::new()).help("SKU code from `bl blox skus`"))
                .arg(Arg::new("multiple").long("multiple").value_name("COUNT").default_value("1").value_parser(clap::value_parser!(i32).range(1..)).help("SKU multiple")),
        )
        .subcommand(
            Command::new("exec")
                .about("Run a command on a workstation and follow its output")
                .long_about("Run a literal executable and arguments after --, stream stdout/stderr, and exit with the remote process status. Use explicit sh -c for shell expansion or pipelines. This is noninteractive: stdin and PTY are not supported. Interrupting or disconnecting may leave the command running. --json prints JSONL output events (protobuf bytes use base64), followed by an exit_code event.")
                .arg(Arg::new("workstation").value_name("WORKSTATION").required(true).value_parser(clap::builder::NonEmptyStringValueParser::new()))
                .arg(Arg::new("workdir").long("workdir").value_name("PATH").value_parser(clap::builder::NonEmptyStringValueParser::new()).help("Remote working directory (defaults to the workstation's configured directory)"))
                .arg(Arg::new("command").value_name("COMMAND").num_args(1..).last(true).required(true).help("Executable and arguments passed literally to the remote process")),
        )
        .subcommand(lifecycle_command("suspend", "Request workstation suspension"))
        .subcommand(lifecycle_command("resume", "Request workstation resumption"))
        .subcommand(lifecycle_command("delete", "Request workstation deletion"))
        .subcommand(
            Command::new("get")
                .about("Get a workstation by canonical name or full ID")
                .arg(Arg::new("workstation").value_name("WORKSTATION").required(true).value_parser(clap::builder::NonEmptyStringValueParser::new())),
        ))
}

fn lifecycle_command(name: &'static str, about: &'static str) -> Command {
    Command::new(name).about(about)
        .long_about("Request this transition for a workstation identified by canonical name or full ID. Reports the server response without waiting for the final state; inspect progress with `bl blox get <id>`. Use the full ID for an archived workstation.")
        .arg(Arg::new("workstation").value_name("WORKSTATION").required(true).value_parser(clap::builder::NonEmptyStringValueParser::new()))
}

fn endpoint_arg(command: Command) -> Command {
    command.arg(
        Arg::new("blox-base-url")
            .long("base-url")
            .visible_alias("control-plane-url")
            .env(ENDPOINT_ENV)
            .global(true)
            .value_name("URL")
            .help(
                "Approved BuilderLab Blox control-plane URL (defaults to your login environment)",
            ),
    )
}

pub fn describe_commands() -> Value {
    super::description::describe_command_tree(&command())
}

pub fn run(matches: &ArgMatches) -> Result<()> {
    runner::run(matches, dispatch)
}

fn dispatch(config: &SkillsConfig, matches: &ArgMatches) -> Result<()> {
    let (operation, args) = matches.subcommand().context("expected a blox subcommand")?;
    if operation == "list"
        && args.get_one::<i32>("limit") == Some(&0)
        && args
            .get_one::<i32>("offset")
            .is_some_and(|offset| *offset > 0)
    {
        return Err(failure(
            exit_codes::GENERAL,
            "invalid_pagination",
            "--offset requires a nonzero --limit",
        ));
    }
    if operation == "exec"
        && args
            .get_many::<String>("command")
            .and_then(|mut command| command.next())
            .is_some_and(|command| command.is_empty())
    {
        return Err(failure(
            exit_codes::GENERAL,
            "invalid_command",
            "The remote executable must not be empty",
        ));
    }
    let endpoint = args
        .get_one::<String>("blox-base-url")
        .cloned()
        .map(Ok)
        .unwrap_or_else(|| default_endpoint(&config.kgoose_base_url))?;
    validate_endpoint(&endpoint)?;
    runner::ensure_org_configured(config)?;
    let storage = default_session_storage(config)?;
    let verified = verify_stored_session(config, storage.as_ref())
        .map_err(map_error)?
        .ok_or_else(|| {
            failure(
                exit_codes::AUTH_REQUIRED,
                "auth_required",
                "BuilderLab CLI auth is required; run `bl auth login`",
            )
        })?;
    let secret = verified
        .credential
        .session_credential_header_value()
        .ok_or_else(|| {
            failure(
                exit_codes::AUTH_REQUIRED,
                "auth_required",
                "BuilderLab CLI auth is required; run `bl auth login`",
            )
        })?;
    // Test-only remapping leaves production origin validation and auth intact.
    #[cfg(test)]
    let endpoint = std::env::var("BL_BLOX_E2E_ENDPOINT").unwrap_or(endpoint);
    let client = blox::Client::new(&endpoint)?.with_session_credential(&secret)?;
    config.style.verbose(&format!("Blox {operation}"));
    match operation {
        "exec" => run_execute(config, args, &client),
        "suspend" | "resume" | "delete" => run_lifecycle(config, args, &client, operation),
        "skus" => {
            let response = client.list_compute_providers().map_err(map_error)?;
            if config.json {
                print_json(&response)
            } else {
                if response.compute_skus.is_empty() {
                    println!("No workstation SKUs are available for your account.");
                } else {
                    println!("CODE\tNAME\tMAX MULTIPLE\tPROVIDER");
                    for sku in &response.compute_skus {
                        println!(
                            "{}\t{}\t{}\t{}",
                            terminal_safe_text(&sku.code),
                            terminal_safe_text(&sku.display_name),
                            sku.max_multiple,
                            terminal_safe_text(&sku.compute_provider)
                        );
                    }
                }
                Ok(())
            }
        }
        "create" => {
            let request = StartWorkstationRequest {
                name: args.get_one::<String>("name").cloned(),
                compute_sku: Some(ComputeSkuSelection {
                    code: args
                        .get_one::<String>("sku")
                        .context("expected SKU code")?
                        .clone(),
                    multiple: *args
                        .get_one::<i32>("multiple")
                        .context("expected SKU multiple")?,
                }),
                creation_client: "builderlab_cli".to_string(),
                ..Default::default()
            };
            let response = client
                .start_workstation(&request)
                .map_err(map_create_error)?;
            if response.workstation_id.is_empty() {
                return Err(create_unknown_outcome());
            }
            if config.json {
                print_json(&response)
            } else {
                println!("ID: {}", terminal_safe_text(&response.workstation_id));
                println!("Status: {}", status_text(response.status));
                if !response.message.is_empty() {
                    println!("Message: {}", terminal_safe_text(&response.message));
                }
                println!(
                    "Inspect with `bl blox get {}` (preserve any --base-url override).",
                    terminal_safe_text(&response.workstation_id)
                );
                Ok(())
            }
        }
        "list" => {
            let response = client
                .list_workstations(&ListWorkstationsRequest {
                    include_deleted: Some(args.get_flag("include-deleted")),
                    page_limit: *args
                        .get_one::<i32>("limit")
                        .context("expected result limit")?,
                    page_offset: *args
                        .get_one::<i32>("offset")
                        .context("expected result offset")?,
                    skip_access_details: true,
                })
                .map_err(map_error)?;
            if config.json {
                print_json(&response)
            } else {
                if response.workstations.is_empty() {
                    println!("No workstations found.");
                } else {
                    println!("ID\tNAME\tSTATUS\tPROVIDER");
                    for workstation in &response.workstations {
                        println!(
                            "{}\t{}\t{}\t{}",
                            terminal_safe_text(&workstation.workstation_id),
                            terminal_safe_text(&workstation.name),
                            status_text(workstation.status),
                            terminal_safe_text(&workstation.provider)
                        );
                    }
                    println!(
                        "{} of {} workstations",
                        response.workstations.len(),
                        response.total_count
                    );
                }
                Ok(())
            }
        }
        "get" => {
            let identifier = args
                .get_one::<String>("workstation")
                .context("expected workstation name or ID")?;
            let response = client.get_workstation(identifier).map_err(map_error)?;
            let workstation = response.workstation.as_ref().ok_or_else(|| {
                failure(
                    exit_codes::GENERAL,
                    "invalid_response",
                    "Blox returned no workstation",
                )
            })?;
            if config.json {
                print_json(&response)
            } else {
                print_workstation(workstation);
                Ok(())
            }
        }
        _ => anyhow::bail!("expected a blox subcommand"),
    }
}

fn run_lifecycle(
    config: &SkillsConfig,
    args: &ArgMatches,
    client: &blox::Client,
    operation: &str,
) -> Result<()> {
    let selector = args
        .get_one::<String>("workstation")
        .context("expected workstation")?;
    let workstation = client
        .get_workstation(selector)
        .map_err(map_error)?
        .workstation
        .filter(|workstation| !workstation.workstation_id.is_empty())
        .ok_or_else(|| {
            failure(
                exit_codes::GENERAL,
                "invalid_response",
                "Blox returned no workstation ID",
            )
        })?;
    let id = &workstation.workstation_id;
    match operation {
        "suspend" => {
            let response = client
                .suspend_workstation(&SuspendWorkstationRequest {
                    workstation_id: id.clone(),
                })
                .map_err(|error| map_lifecycle_error(error, operation, id))?;
            print_lifecycle_result(
                config,
                operation,
                id,
                LifecycleSummary {
                    workstation_id: &response.workstation_id,
                    status: Some(response.status),
                    success: true,
                    message: &response.message,
                },
                &response,
            )
        }
        "resume" => {
            let response = client
                .resume_workstation(&ResumeWorkstationRequest {
                    workstation_id: id.clone(),
                })
                .map_err(|error| map_lifecycle_error(error, operation, id))?;
            print_lifecycle_result(
                config,
                operation,
                id,
                LifecycleSummary {
                    workstation_id: &response.workstation_id,
                    status: Some(response.status),
                    success: true,
                    message: &response.message,
                },
                &response,
            )
        }
        "delete" => {
            let response = client
                .delete_workstation(&DeleteWorkstationRequest {
                    workstation_id: id.clone(),
                })
                .map_err(|error| map_lifecycle_error(error, operation, id))?;
            print_lifecycle_result(
                config,
                operation,
                id,
                LifecycleSummary {
                    workstation_id: &response.workstation_id,
                    status: None,
                    success: response.success,
                    message: &response.message,
                },
                &response,
            )
        }
        _ => anyhow::bail!("expected a lifecycle operation"),
    }
}

struct LifecycleSummary<'a> {
    workstation_id: &'a str,
    status: Option<i32>,
    success: bool,
    message: &'a str,
}

fn print_lifecycle_result<T: Serialize>(
    config: &SkillsConfig,
    operation: &str,
    requested_id: &str,
    summary: LifecycleSummary<'_>,
    response: &T,
) -> Result<()> {
    if summary.workstation_id != requested_id {
        return Err(lifecycle_unknown(
            operation,
            requested_id,
            Some(summary.message),
        ));
    }
    if !summary.success
        || matches!(summary.status, Some(status) if status == WorkstationStatus::Error as i32 || status == WorkstationStatus::Degraded as i32)
    {
        return Err(failure(
            exit_codes::GENERAL,
            "lifecycle_failed",
            format!(
                "Blox {operation} failed for workstation {}: {}",
                terminal_safe_text(requested_id),
                if summary.message.is_empty() {
                    "server reported an unsuccessful transition".to_string()
                } else {
                    terminal_safe_text(summary.message)
                }
            ),
        ));
    }
    if let Some(status) = summary.status {
        let accepted = WorkstationStatus::try_from(status).is_ok_and(|status| match operation {
            "suspend" => matches!(
                status,
                WorkstationStatus::Suspending
                    | WorkstationStatus::Suspended
                    | WorkstationStatus::Deleting
                    | WorkstationStatus::Deleted
            ),
            "resume" => matches!(
                status,
                WorkstationStatus::Queued
                    | WorkstationStatus::Creating
                    | WorkstationStatus::Starting
                    | WorkstationStatus::Running
            ),
            _ => false,
        });
        if !accepted {
            return Err(lifecycle_unknown(
                operation,
                requested_id,
                Some(summary.message),
            ));
        }
    }
    if config.json {
        return print_json(response);
    }
    println!("Request accepted: {operation}");
    println!("ID: {}", terminal_safe_text(summary.workstation_id));
    if let Some(status) = summary.status {
        println!("Server status: {}", status_text(status));
    }
    if !summary.message.is_empty() {
        println!("Message: {}", terminal_safe_text(summary.message));
    }
    println!(
        "Inspect progress with `bl blox get {}` (preserve any --base-url override).",
        terminal_safe_text(requested_id)
    );
    Ok(())
}

fn lifecycle_unknown(operation: &str, id: &str, server_message: Option<&str>) -> anyhow::Error {
    let mut message = format!("Blox {operation} result is unknown for workstation {}. Inspect `bl blox get {}` with the same Blox endpoint before trying again; the transition may already be underway. Preserve any --base-url override.", terminal_safe_text(id), terminal_safe_text(id));
    if let Some(server_message) = server_message.filter(|message| !message.is_empty()) {
        message.push_str(&format!(
            " Server message: {}",
            terminal_safe_text(server_message)
        ));
    }
    failure(exit_codes::NETWORK, "lifecycle_outcome_unknown", message)
}

fn map_lifecycle_error(error: anyhow::Error, operation: &str, id: &str) -> anyhow::Error {
    if let Some(rpc) = error.downcast_ref::<blox::RpcError>() {
        if !matches!(
            rpc.code.as_str(),
            "unavailable" | "deadline_exceeded" | "unknown" | "internal" | "data_loss"
        ) {
            return map_error(error);
        }
    }
    lifecycle_unknown(operation, id, None)
}

fn run_execute(config: &SkillsConfig, args: &ArgMatches, client: &blox::Client) -> Result<()> {
    let selector = args
        .get_one::<String>("workstation")
        .context("expected workstation")?;
    let workstation = client
        .get_workstation(selector)
        .map_err(map_error)?
        .workstation
        .filter(|workstation| !workstation.workstation_id.is_empty())
        .ok_or_else(|| {
            failure(
                exit_codes::GENERAL,
                "invalid_response",
                "Blox returned no workstation ID",
            )
        })?;
    let mut command = args
        .get_many::<String>("command")
        .context("expected command")?;
    let executable = command.next().context("expected executable")?.clone();
    let response = client
        .execute_process(&ExecuteProcessRequest {
            workstation_id: workstation.workstation_id.clone(),
            command: executable,
            args: command.cloned().collect(),
            working_dir: args
                .get_one::<String>("workdir")
                .cloned()
                .unwrap_or_default(),
            ..Default::default()
        })
        .map_err(|error| map_execute_start_error(error, &workstation.workstation_id))?;
    if response.command_id.is_empty() {
        return Err(execute_start_unknown(&workstation.workstation_id));
    }
    let command_id = response.command_id;
    config
        .style
        .verbose(&format!("Following Blox command {command_id}"));
    let mut exit_code = None;
    client
        .stream_command_output(
            &StreamCommandOutputRequest {
                workstation_id: workstation.workstation_id.clone(),
                command_id: command_id.clone(),
                follow: true,
                ..Default::default()
            },
            |output| {
                if config.json {
                    write_json_line(&serde_json::json!({
                        "workstation_id":workstation.workstation_id,
                        "command_id":command_id,
                        "output":output,
                    }))?;
                } else if !output.data.is_empty() {
                    match output.stream {
                        1 => {
                            let mut stdout = std::io::stdout().lock();
                            stdout.write_all(&output.data)?;
                            stdout.flush()?;
                        }
                        2 => {
                            let mut stderr = std::io::stderr().lock();
                            stderr.write_all(&output.data)?;
                            stderr.flush()?;
                        }
                        _ => anyhow::bail!("Blox returned output with an unsupported stream type"),
                    }
                }
                if let Some(code) = output.exit_code {
                    exit_code = Some(code);
                }
                Ok(())
            },
        )
        .map_err(|_| execute_follow_failed(&workstation.workstation_id, &command_id))?;
    let exit_code =
        exit_code.ok_or_else(|| execute_follow_failed(&workstation.workstation_id, &command_id))?;
    if config.json {
        write_json_line(
            &serde_json::json!({"workstation_id":workstation.workstation_id, "command_id":command_id, "exit_code":exit_code}),
        )?;
    }
    if exit_code != 0 {
        return Err(anyhow::Error::new(SilentJsonExit(exit_code)));
    }
    Ok(())
}

fn write_json_line(value: &Value) -> Result<()> {
    let mut stdout = std::io::stdout().lock();
    serde_json::to_writer(&mut stdout, value).context("write Blox JSONL output")?;
    stdout
        .write_all(b"\n")
        .context("write Blox JSONL newline")?;
    stdout.flush().context("flush Blox JSONL output")
}

fn execute_start_unknown(workstation_id: &str) -> anyhow::Error {
    failure(exit_codes::NETWORK, "execute_outcome_unknown", format!("Blox execution result is unknown on workstation {}. Inspect its commands in Blox before running it again; the command may already be running. Preserve any --base-url override.", terminal_safe_text(workstation_id)))
}

fn map_execute_start_error(error: anyhow::Error, workstation_id: &str) -> anyhow::Error {
    if let Some(rpc) = error.downcast_ref::<blox::RpcError>() {
        if !matches!(
            rpc.code.as_str(),
            "unavailable" | "deadline_exceeded" | "unknown" | "internal" | "data_loss"
        ) {
            return map_error(error);
        }
    }
    execute_start_unknown(workstation_id)
}

fn execute_follow_failed(workstation_id: &str, command_id: &str) -> anyhow::Error {
    failure(exit_codes::NETWORK, "execute_output_incomplete", format!("Could not confirm the result of Blox command {} on workstation {}. The command may still be running; inspect it in Blox before running it again. Preserve any --base-url override.", terminal_safe_text(command_id), terminal_safe_text(workstation_id)))
}

fn default_endpoint(auth_base_url: &str) -> Result<String> {
    let origin = url::Url::parse(auth_base_url)
        .context("parse BuilderLab auth URL")?
        .origin()
        .ascii_serialization();
    let endpoint = match origin.as_str() {
        "https://test.blockstaging.build" => "https://blox.test.blockstaging.build",
        "https://app.builderlabstaging.xyz" => "https://blox.public.builderlabstaging.xyz",
        "https://app.builderlab.xyz" => "https://blox.public.builderlab.xyz",
        "https://block.builderlab.xyz" => return Err(failure(exit_codes::GENERAL, "blox_unavailable", "Blox is not deployed in this BuilderLab environment")),
        _ => return Err(failure(exit_codes::GENERAL, "endpoint_required", "No Blox endpoint is configured for this BuilderLab environment; set an approved ingress with --base-url or BL_BLOX_CONTROL_PLANE_URL")),
    };
    Ok(endpoint.to_string())
}

fn validate_endpoint(endpoint: &str) -> Result<()> {
    let url = url::Url::parse(endpoint).context("parse Blox control-plane URL")?;
    let approved = url.scheme() == "https"
        && url.port_or_known_default() == Some(443)
        && url.username().is_empty()
        && url.password().is_none()
        && url.path() == "/"
        && url.query().is_none()
        && url.fragment().is_none()
        && url.host_str().is_some_and(|host| {
            APPROVED_HOSTS
                .iter()
                .any(|approved| host.eq_ignore_ascii_case(approved))
        });
    if !approved {
        return Err(failure(
            exit_codes::GENERAL,
            "invalid_endpoint",
            "Blox control-plane URL must target an approved BuilderLab ingress over HTTPS",
        ));
    }
    Ok(())
}

fn status_text(status: i32) -> String {
    WorkstationStatus::try_from(status)
        .map(|status| {
            status
                .as_str_name()
                .trim_start_matches("WORKSTATION_STATUS_")
                .to_ascii_lowercase()
        })
        .unwrap_or_else(|_| format!("unknown({status})"))
}

fn print_workstation(workstation: &WorkstationSummary) {
    for (label, value) in [
        ("ID", workstation.workstation_id.as_str()),
        ("Name", workstation.name.as_str()),
        ("Provider", workstation.provider.as_str()),
        ("Created", workstation.created_at.as_str()),
        ("Last used", workstation.last_used_at.as_str()),
        ("Message", workstation.message.as_str()),
    ] {
        println!("{label}: {}", terminal_safe_text(value));
    }
    println!("Status: {}", status_text(workstation.status));
    if let Some(label) = &workstation.display_name {
        println!("Display name: {}", terminal_safe_text(label));
    }
}

fn create_unknown_outcome() -> anyhow::Error {
    failure(exit_codes::NETWORK, "create_outcome_unknown", "Blox creation result is unknown. Inspect `bl blox list` or `bl blox get <name>` before trying again; the workstation may already exist. Preserve any --base-url override when checking.")
}

fn map_create_error(error: anyhow::Error) -> anyhow::Error {
    if let Some(rpc) = error.downcast_ref::<blox::RpcError>() {
        if !matches!(
            rpc.code.as_str(),
            "unavailable" | "deadline_exceeded" | "unknown" | "internal" | "data_loss"
        ) {
            return map_error(error);
        }
    }
    create_unknown_outcome()
}

fn map_error(error: anyhow::Error) -> anyhow::Error {
    if let Some(rpc) = error.downcast_ref::<blox::RpcError>() {
        let exit_code = match rpc.code.as_str() {
            "unauthenticated" => exit_codes::AUTH_REQUIRED,
            "permission_denied" => exit_codes::FORBIDDEN,
            "unavailable" | "deadline_exceeded" => exit_codes::NETWORK,
            _ => exit_codes::GENERAL,
        };
        let message = if rpc.code == "unauthenticated" {
            "Blox authentication failed; run `bl auth login`".to_string()
        } else {
            format!("Blox {}: {}", rpc.code, terminal_safe_text(&rpc.message))
        };
        return failure(exit_code, &rpc.code, message);
    }
    if error.chain().any(|cause| cause.is::<reqwest::Error>()) {
        return failure(exit_codes::NETWORK, "network_error", format!("{error:#}"));
    }
    error
}

